/** Draws every logo file from the one glyph path in src/everything-ui/icons.tsx:
 *  the website's logo SVG, its favicons, the extension's icons, and the icons
 *  the browser stores ask for.
 *  The logo comes in two forms. The plain blue notes are for places whose
 *  colours we control, such as the website's header. Every icon is white notes
 *  on a blue tile instead. A toolbar or a tab strip can be any grey, and plain
 *  blue notes vanish on a mid grey: on the grey Chrome puts behind a hovered
 *  toolbar button they measured 1.0 to 1, the same brightness. White on the
 *  blue tile is 5.2 to 1 on every background.
 *  It renders through Chrome with Playwright, because Playwright is already a
 *  dependency of this repo. macOS has no reliable command line SVG rasterizer.
 *  sips mangles SVGs, and rsvg-convert is not installed.
 *  The files are checked in, so run this again only when the glyph changes:
 *
 *    bun run scripts/generate-logo-assets.ts
 */
import { writeFileSync } from "node:fs";
import path from "node:path";
import { chromium } from "playwright";
import { NOTE_STACK_GLYPH_PATH } from "../src/everything-ui/icons";

const ROOT = path.resolve(import.meta.dir, "..");
const LOGO_PATH = path.join(ROOT, "src/everything-ui/assets/logo.svg");
const EXTENSION_ICONS = path.join(ROOT, "src/everything-extension/public/icon");
const STORE_ASSETS = path.join(ROOT, "src/everything-extension/store-assets");
const WEBSITE_ASSETS = path.join(ROOT, "src/everything-web/src/assets");
const ICON_PATH = path.join(WEBSITE_ASSETS, "icon.svg");

// The brand blue, the primary colour in src/everything-ui/tokens.css.
const LOGO_COLOR = "#2563eb";
const GENERATED_NOTE = "<!-- Generated by scripts/generate-logo-assets.ts from NOTE_STACK_GLYPH_PATH in src/everything-ui/icons.tsx. -->";
// The glyph spans 18 of its 24 units, from 3 to 21. Cropping the view to that
// square makes the mark fill the whole image.
const GLYPH_SPAN = 18;
const LOGO_SVG = `<svg xmlns="http://www.w3.org/2000/svg" width="128" height="128" viewBox="3 3 18 18">
  ${GENERATED_NOTE}
  <path fill="${LOGO_COLOR}" fill-rule="evenodd" d="${NOTE_STACK_GLYPH_PATH}"/>
</svg>
`;

// How much of the tile's width the notes take, and how round the tile's
// corners are, both as shares of the tile. Jim picked the notes' share in the
// logo explorer with "Fit to canvas" on a backdrop, which leaves 24 of 128
// units on each side. The explorer's "White on a blue tile" preset uses the
// same proportions.
const MARK_SHARE_OF_TILE = 80 / 128;
const TILE_CORNER_SHARE = 0.22;

/** White notes on a blue tile, on the glyph's 24 unit grid. `cornerShare` 0
 *  gives a square, for iOS, which rounds the corners itself. */
function tileSvg(cornerShare: number) {
  const scale = (MARK_SHARE_OF_TILE * 24) / GLYPH_SPAN;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="128" height="128" viewBox="0 0 24 24">
  ${GENERATED_NOTE}
  <rect width="24" height="24" rx="${cornerShare * 24}" fill="${LOGO_COLOR}"/>
  <path fill="#ffffff" fill-rule="evenodd" transform="translate(12 12) scale(${scale.toFixed(4)}) translate(-12 -12)" d="${NOTE_STACK_GLYPH_PATH}"/>
</svg>
`;
}

const ICON_SVG = tileSvg(TILE_CORNER_SHARE);

interface Raster {
  file: string;
  svg: string;
  size: number;
  /** How wide the SVG is drawn inside the square. The rest stays transparent. */
  artwork: number;
}

// The Chrome Web Store asks for the 128 pixel icon to carry its artwork at 96
// by 96 inside a transparent margin. The manifest's 128 pixel icon is the same
// file. The smaller toolbar sizes fill their whole square.
const CHROME_128 = { svg: ICON_SVG, size: 128, artwork: 96 };
const RASTERS: Raster[] = [
  { file: path.join(EXTENSION_ICONS, "16.png"), svg: ICON_SVG, size: 16, artwork: 16 },
  { file: path.join(EXTENSION_ICONS, "32.png"), svg: ICON_SVG, size: 32, artwork: 32 },
  { file: path.join(EXTENSION_ICONS, "48.png"), svg: ICON_SVG, size: 48, artwork: 48 },
  { file: path.join(EXTENSION_ICONS, "128.png"), ...CHROME_128 },
  { file: path.join(STORE_ASSETS, "chrome-web-store-128.png"), ...CHROME_128 },
  // Mozilla's add-on listing wants a 128 pixel icon that fills its square.
  { file: path.join(STORE_ASSETS, "firefox-add-ons-128.png"), svg: ICON_SVG, size: 128, artwork: 128 },
  // Browsers without SVG favicons take the PNG.
  { file: path.join(WEBSITE_ASSETS, "favicon-32.png"), svg: ICON_SVG, size: 32, artwork: 32 },
  // iOS rounds a home screen icon's corners itself and puts anything
  // transparent on black, so this one is a full square.
  { file: path.join(WEBSITE_ASSETS, "apple-touch-icon.png"), svg: tileSvg(0), size: 180, artwork: 180 },
];

writeFileSync(LOGO_PATH, LOGO_SVG);
writeFileSync(ICON_PATH, ICON_SVG);
console.log(`wrote ${LOGO_PATH} and ${ICON_PATH}`);

// Chrome itself on a Mac, Playwright's own Chromium elsewhere.
const browser = await chromium.launch(process.platform === "darwin" ? { channel: "chrome" } : {});
const page = await browser.newPage();

for (const { file, svg, size, artwork } of RASTERS) {
  const inset = (size - artwork) / 2;
  await page.setViewportSize({ width: size, height: size });
  await page.setContent(
    `<style>html,body{margin:0;background:transparent}svg{display:block;width:${artwork}px;height:${artwork}px;margin:${inset}px}</style>${svg}`,
  );
  await page.screenshot({ path: file, omitBackground: true });
  console.log(`wrote ${file}`);
}
await browser.close();

NMR = "NEEDS_MORE_RATINGS"
NOT_HELPFUL = "CURRENTLY_RATED_NOT_HELPFUL"
NOTE_NOT_NEEDED = "notHelpfulNoteNotNeeded"
MIN_NOTE_NOT_NEEDED_RATINGS = 2


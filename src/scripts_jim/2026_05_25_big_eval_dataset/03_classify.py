COMPILED = {k: [re.compile(p, re.I) for p in pats] for k, pats in CATEGORY_PATTERNS.items()}


def classify(text: str) -> list[str]:
    return [k for k, pats in COMPILED.items() if any(p.search(text) for p in pats)]


def derive_role(rec: dict) -> tuple[str, str | None, bool]:
    status = rec.get("current_status")
    nnn = (rec.get("not_helpful_tag_counts") or {}).get(NOTE_NOT_NEEDED, 0)
    if status == NOT_HELPFUL:
        reason = rec.get("dominant_not_helpful_reason")
        if reason == NOTE_NOT_NEEDED:
            return "no_note_needed", "no", True  # confirm: do I agree no note was needed?
        return f"unhelpful_{reason or 'unspecified'}", "yes", True  # confirm a better note is possible
    if status == HELPFUL:
        return "helpful_reference", "yes", False
    if status == NMR and nnn >= MIN_NOTE_NOT_NEEDED_RATINGS:
        return "no_note_needed", "no", True  # NMR + note-not-needed signal — confirm agreement
    return "nmr_other", None, False


def main() -> None:
    rows, role_counts, cat_counts = [], Counter(), Counter()
    with CORPUS.open() as f:
        for ln in f:
            rec = json.loads(ln)
            text = f"{rec.get('note_text','')} {rec.get('tweet_text','') or ''}"
            cats = classify(text)
            role, needs_note, needs_confirm = derive_role(rec)
            rec.update(categories=cats, role=role, needs_note=needs_note, needs_confirm=needs_confirm)
            rows.append(rec)
            role_counts[role] += 1
            for c in (cats or ["(uncategorized)"]):
                cat_counts[c] += 1
    with OUT.open("w") as f:
        for r in rows:
            f.write(json.dumps(r) + "\n")
    print(f"wrote {len(rows)} -> corpus_labeled.jsonl\n")
    print("roles:")
    for r, c in role_counts.most_common():
        print(f"  {r}: {c:,}")
    print("\ncategory hits (multi-label):")
    for c, n in cat_counts.most_common():
        print(f"  {c}: {n:,}")


if __name__ == "__main__":
    main()

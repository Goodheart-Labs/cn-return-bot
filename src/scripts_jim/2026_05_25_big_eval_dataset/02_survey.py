"""
Phase 2 helper: survey the corpus to ground a data-driven category map.

Does NOT decide categories — Claude reads the outputs and writes CATEGORIES.md.
Produces two things (no LLM tokens spent here):
  - survey_stats.md         : keyword-prevalence skeleton over ALL 104k notes, to
                              size categories realistically.
  - _cache/survey_sample.jsonl : a diverse, capped sample for Claude to read and
                              cluster into the territory map.

  uv run src/scripts_jim/2026_05_25_big_eval_dataset/02_survey.py
"""
import json
import random
import re
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
BIG_EVAL = HERE.parent.parent.parent / "datasets" / "big_eval"
CORPUS = BIG_EVAL / "corpus.jsonl"
CACHE = BIG_EVAL / "_cache"

HELPFUL = "CURRENTLY_RATED_HELPFUL"
NMR = "NEEDS_MORE_RATINGS"
NOT_HELPFUL = "CURRENTLY_RATED_NOT_HELPFUL"
NOTE_NOT_NEEDED = "notHelpfulNoteNotNeeded"
SEED = 42
NOTE_TRUNC = 600
TWEET_TRUNC = 400

# Keyword probes — crude, only to *size* likely territory categories. The real
# taxonomy comes from reading the sample.
PROBES: dict[str, list[str]] = {
    "ai_generated_media": [r"\bai[- ]generated\b", r"\bgenerated by ai\b", r"\bdeepfake", r"\bsora\b",
                            r"\bmidjourney\b", r"\bsynthetic (image|video|media)", r"\bnot a real (photo|video|image)",
                            r"\bai image\b", r"\bai video\b", r"\bdigitally (created|generated)"],
    "misattributed_old_media": [r"\bold (video|footage|photo|image|clip)", r"\bunrelated\b", r"\bactually from\b",
                                 r"\bfootage (is )?from\b", r"\bpredates\b", r"\bmiscaption", r"\bout of context\b",
                                 r"\bnot (related|from) (the|this)", r"\bfrom \d{4}\b"],
    "manipulated_media": [r"\bdoctored\b", r"\baltered\b", r"\bedited (image|video|photo)", r"\bphotoshop", r"\bmanipulated\b"],
    "fabricated_quote_or_screenshot": [r"\bdid not say\b", r"\bnever said\b", r"\bno record of\b", r"\bfabricated\b",
                                        r"\bmisquote", r"\bfake (screenshot|tweet|post|headline)", r"\bno evidence .* said"],
    "overhype_research": [r"\bno (peer|published) ", r"\bnot peer[- ]reviewed", r"\bpreprint\b", r"\bexaggerat",
                           r"\boverstat", r"\bmisrepresent", r"\bthe study (did|does) not", r"\bno study\b"],
    "satire_parody": [r"\bsatir", r"\bparod", r"\bnot a real (account|person)", r"\bspoof", r"\bjoke account\b"],
    "statistics_numbers": [r"\d+%", r"\bpercent\b", r"\bstatistic", r"\bthe (number|figure|data) ", r"\bper capita\b"],
    "scam_crypto": [r"\bscam\b", r"\bcrypto", r"\bgiveaway\b", r"\bphishing\b", r"\bponzi\b", r"\bfraudulent\b"],
    "health_medical": [r"\bvaccin", r"\bcovid\b", r"\bfda\b", r"\bcdc\b", r"\bclinical\b", r"\bdisease\b", r"\bcancer\b"],
    "politics_policy": [r"\bbill\b", r"\bsenate\b", r"\bcongress\b", r"\belection\b", r"\bvote(d|s)?\b", r"\blegislation\b",
                         r"\bexecutive order\b", r"\btariff", r"\bpolicy\b"],
    "ai_tech_industry": [r"\bopenai\b", r"\banthropic\b", r"\bagi\b", r"\bllm\b", r"\bchatgpt\b", r"\bdata ?center",
                          r"\bcompute\b", r"\bgpu\b", r"\bpentagon\b"],
    "animal_welfare": [r"\banimal (welfare|cruelty|agriculture)", r"\bfactory farm", r"\bvegan\b", r"\blivestock\b", r"\bslaughter"],
    "war_geopolitics": [r"\bukraine\b", r"\bgaza\b", r"\bisrael\b", r"\brussia\b", r"\bmilitary\b", r"\bairstrike\b", r"\bwar\b"],
}


def truncate(s: str | None, n: int) -> str:
    s = (s or "").replace("\n", " ").strip()
    return s if len(s) <= n else s[:n] + "…"


def load_corpus() -> list[dict]:
    with CORPUS.open() as f:
        return [json.loads(ln) for ln in f]


def keyword_stats(rows: list[dict]) -> str:
    compiled = {k: [re.compile(p, re.I) for p in pats] for k, pats in PROBES.items()}
    counts: Counter = Counter()
    for r in rows:
        blob = f"{r.get('note_text','')} {r.get('tweet_text','') or ''}"
        for k, pats in compiled.items():
            if any(p.search(blob) for p in pats):
                counts[k] += 1
    total = len(rows)
    lines = ["# big_eval survey — keyword prevalence (sizing skeleton)\n",
             f"Scanned {total:,} corpus rows. Probes are crude; real categories come from the sample.\n",
             "| probe | matches | % |", "|---|---:|---:|"]
    for k, c in counts.most_common():
        lines.append(f"| {k} | {c:,} | {100*c/total:.1f}% |")
    return "\n".join(lines) + "\n"


def sample(rows: list[dict]) -> list[dict]:
    rng = random.Random(SEED)
    by_id = {r["note_id"]: r for r in rows}

    not_helpful = [r for r in rows if r.get("current_status") == NOT_HELPFUL]
    helpful_ai = [r for r in rows if r.get("current_status") == HELPFUL and r.get("source") == "ai_author"]
    nmr = [r for r in rows if r.get("current_status") == NMR]
    nmr_nnn = [r for r in nmr if r.get("not_helpful_tag_counts", {}).get(NOTE_NOT_NEEDED, 0) >= 2]
    db_helpful = [r for r in rows if str(r.get("source", "")).startswith("db_")]
    db_high_impr = sorted(db_helpful, key=lambda r: -(r.get("impressions") or 0))

    picks: dict[str, dict] = {}

    # NOT_HELPFUL stratified by dominant reason (min coverage each).
    by_reason: dict[str, list] = {}
    for r in not_helpful:
        by_reason.setdefault(r.get("dominant_not_helpful_reason") or "(none)", []).append(r)
    for reason, group in by_reason.items():
        rng.shuffle(group)
        for r in group[:12]:
            picks[r["note_id"]] = r

    # Helpful AI-author: top by rating_volume + random.
    helpful_ai_sorted = sorted(helpful_ai, key=lambda r: -(r.get("rating_volume") or 0))
    for r in helpful_ai_sorted[:35] + rng.sample(helpful_ai, min(35, len(helpful_ai))):
        picks[r["note_id"]] = r

    # NMR note-not-needed (the adversarial no-note half).
    for r in rng.sample(nmr_nnn, min(50, len(nmr_nnn))):
        picks[r["note_id"]] = r

    # DB helpful with tweet text — top impressions + random (these carry tweet_text).
    for r in db_high_impr[:45] + rng.sample(db_helpful, min(35, len(db_helpful))):
        picks[r["note_id"]] = r

    # Plain random NMR.
    for r in rng.sample(nmr, min(25, len(nmr))):
        picks[r["note_id"]] = r

    out = []
    for r in picks.values():
        out.append({
            "note_id": r["note_id"], "tweet_id": r.get("tweet_id"),
            "url": f"https://x.com/i/status/{r.get('tweet_id')}",
            "source": r.get("source"), "current_status": r.get("current_status"),
            "dominant_not_helpful_reason": r.get("dominant_not_helpful_reason"),
            "rating_volume": r.get("rating_volume"), "impressions": r.get("impressions"),
            "has_video": r.get("has_video"),
            "note_text": truncate(r.get("note_text"), NOTE_TRUNC),
            "tweet_text": truncate(r.get("tweet_text"), TWEET_TRUNC),
        })
    rng.shuffle(out)
    return out


def main() -> None:
    rows = load_corpus()
    (BIG_EVAL / "survey_stats.md").write_text(keyword_stats(rows))
    print(f"wrote survey_stats.md")
    samp = sample(rows)
    CACHE.mkdir(parents=True, exist_ok=True)
    with (CACHE / "survey_sample.jsonl").open("w") as f:
        for r in samp:
            f.write(json.dumps(r) + "\n")
    print(f"wrote {len(samp)} -> _cache/survey_sample.jsonl")
    by_status = Counter(r["current_status"] for r in samp)
    by_source = Counter(r["source"] for r in samp)
    print("sample by status:", dict(by_status))
    print("sample by source:", dict(by_source))


if __name__ == "__main__":
    main()
